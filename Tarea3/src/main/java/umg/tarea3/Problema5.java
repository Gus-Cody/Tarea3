    private void btnCrearCanciónActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearCanciónActionPerformed
        // TODO add your handling code here:
        
        
        
        String titulo = txtTitulo.getText().trim();
        String interprete = txtInterprete.getText().trim();
        String genero = txtGenero.getText().trim();
        
        if (titulo.isEmpty() || interprete.isEmpty() || genero.isEmpty()) {
        
            JOptionPane.showMessageDialog(this, "Completa título, intérprete y género");
        return;
        }
        
        int duracion;
        
        
        try {
        duracion = Integer.parseInt(txtDuracion.getText().trim());
        }
        
        catch (NumberFormatException ex) {
        
            JOptionPane.showMessageDialog(this, "La duración debe ser un número entero de segundos");
        return;
        }
        
        Cancion cancion = new Cancion();
        cancion.titulo = titulo;
        cancion.duracionSegundos = duracion;
        cancion.genero = genero;
        cancion.nombreArtista = interprete;
        
        taResultados.append("CANCIÓN\n");
        taResultados.append("  Título: " + cancion.titulo + "\n");
        taResultados.append("  Intérprete: " + cancion.nombreArtista + "\n");
        taResultados.append("  Duración: " + cancion.duracionSegundos + " segundos\n");
        taResultados.append("  Género: " + cancion.genero + "\n");

        
       
        txtTitulo.setText("");
        txtInterprete.setText("");
        txtDuracion.setText("");
        txtGenero.setText("");

    }//GEN-LAST:event_btnCrearCanciónActionPerformed

