    private void btnCrearArtistaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearArtistaActionPerformed
        // TODO add your handling code here:
        String nombre = txtNombreArtista.getText().trim();
    String pais = txtPais.getText().trim();

    if (nombre.isEmpty() || pais.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Completa el nombre y el país");
    return;
    
    
    }

    int oyentes;
    try {
    oyentes = Integer.parseInt(txtOyentes.getText().trim());
    } catch (NumberFormatException ex) {
    JOptionPane.showMessageDialog(this, "Los oyentes mensuales deben ser un número entero");
    return;
    }

    Artista artista = new Artista();
    artista.nombre = nombre;
    artista.paisOrigen = pais;
    artista.oyentesMensuales = oyentes;


    taResultados.append("ARTISTA\n");

    taResultados.append("  Nombre: " + artista.nombre + "\n");

    taResultados.append("  País de origen: " + artista.paisOrigen + "\n");

    taResultados.append("  Oyentes mensuales: " + artista.oyentesMensuales + "\n");



    txtNombreArtista.setText("");

    txtPais.setText("");

    txtOyentes.setText("");
        
        
    }//GEN-LAST:event_btnCrearArtistaActionPerformed

