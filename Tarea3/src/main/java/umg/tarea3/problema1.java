    private void btnAgregarRutaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarRutaActionPerformed
        // TODO add your handling code here:
    if (indice < 7) {
    km[indice] = Double.parseDouble(txtKm.getText());
    indice++;
    txtKm.setText("");
} else {
    JOptionPane.showMessageDialog(this, "Ya ingresaste las 7 rutas");
}   
        
    }//GEN-LAST:event_btnAgregarRutaActionPerformed

    private void btnGenerarReporteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarReporteActionPerformed
        // TODO add your handling code here:
        if (indice < 7) {
    JOptionPane.showMessageDialog(this, "Faltan rutas por ingresar");
    return;
    }

    double total = 0;
    for (int i = 0; i < km.length; i++) {
    total += km[i];
    }
    double promedio = total / km.length;

    try (FileWriter fw = new FileWriter("temp/ismael_reporte_rutas.txt")) {
    fw.write("Reporte Semanal de Rutas\n");
    fw.write("Total de Kilómetros: " + total + "\n");
    fw.write("Promedio Diario: " + promedio + "\n");
    JOptionPane.showMessageDialog(this, "Reporte generado en la carpeta temp");
    } catch (IOException ex) {
    System.out.println("Error al escribir: " + ex.getMessage());
    }
        
    }//GEN-LAST:event_btnGenerarReporteActionPerformed

