    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        
    String buscar = txtBuscar.getText().trim();
    boolean encontrado = false;

    for (int i = 0; i < titulos.length; i++) {
    if (buscar.equalsIgnoreCase(titulos[i])) {
        lblAnio.setText(String.valueOf(anios[i]));
        encontrado = true;
        break;
            }
        }

            if (!encontrado) {
    lblAnio.setText("-");
    JOptionPane.showMessageDialog(this, "Álbum no encontrado");
            }
        
        
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        String buscar = txtBuscar.getText().trim();
    int indiceEncontrado = -1;

    for (int i = 0; i < titulos.length; i++) {
    if (buscar.equalsIgnoreCase(titulos[i])) {
        indiceEncontrado = i;
        break;
    }
    }

    if (indiceEncontrado == -1) {
    JOptionPane.showMessageDialog(this, "Álbum no encontrado");
    return;
    }

    int nuevoAnio;
    try {
    nuevoAnio = Integer.parseInt(txtNuevoAnio.getText().trim());
    } catch (NumberFormatException ex) {
    JOptionPane.showMessageDialog(this, "El nuevo año debe ser un número entero");
    return;
    }

    anios[indiceEncontrado] = nuevoAnio;

    try (FileWriter fw = new FileWriter(ruta, false)) {
    for (int i = 0; i < titulos.length; i++) {
        fw.write(titulos[i] + "," + anios[i] + "\n");
    }
    lblAnio.setText(String.valueOf(nuevoAnio));
    JOptionPane.showMessageDialog(this, "Registro actualizado");
    } catch (IOException ex) {
    JOptionPane.showMessageDialog(this, "Error al escribir el archivo: " + ex.getMessage());
    }
        
        
    }//GEN-LAST:event_btnActualizarActionPerformed

