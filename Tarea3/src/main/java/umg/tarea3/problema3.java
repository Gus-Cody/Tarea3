    private void btnCargarDatosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarDatosActionPerformed
        // TODO add your handling code here:
        
    indice = 0;
    
    File archivo = new File(ruta);

    try (Scanner sc = new Scanner(archivo)) {
    while (sc.hasNextLine() && indice < 6) {
        
        String linea = sc.nextLine();
        
        if (!linea.trim().isEmpty()) {
            temperaturas[indice] = Double.parseDouble(linea.trim());
            indice++;
        }
    }
    JOptionPane.showMessageDialog(this, "Datos cargados en memoria");
    } catch (Exception ex) {
    JOptionPane.showMessageDialog(this, "Error al leer el archivo: " + ex.getMessage());
    }


    }//GEN-LAST:event_btnCargarDatosActionPerformed

    private void btnCalcularEstadisticasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularEstadisticasActionPerformed
        // TODO add your handling code here:
       if (indice < 6) {
    
           
           JOptionPane.showMessageDialog(this, "Primero presiona Cargar Datos");
    return;
    }

    double suma = 0;
    int calidos = 0;
    int frescos = 0;

    for (int i = 0; i < temperaturas.length; i++) {
    suma += temperaturas[i];

    if (temperaturas[i] >= 25.0) {
        calidos++;
    } else {
        frescos++;
    }
    }

    double promedio = suma / temperaturas.length;

    taResultado.setText("Análisis Climático\n"  + "------------------\n"
        + "Promedio de Temperatura: " + promedio + "\n"
        + "Días Cálidos (>= 25°): " + calidos + "\n"
        + "Días Frescos (< 25°): " + frescos); 
        
        
    }//GEN-LAST:event_btnCalcularEstadisticasActionPerformed

