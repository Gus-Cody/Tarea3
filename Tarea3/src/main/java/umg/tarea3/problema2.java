    private void btnAgregarTareaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarTareaActionPerformed
        // TODO add your handling code here:
    if (indice < 5) {
        
    tareas[indice] = txtTarea.getText();
    
    taLista.append((indice + 1) + ". " + tareas[indice] + "\n");
    indice++;
    txtTarea.setText("");
    
    } else {
         
        JOptionPane.showMessageDialog(this, "Ya ingresaste las 5 tareas");
    }   
        

    }//GEN-LAST:event_btnAgregarTareaActionPerformed

    private void btnExportarAgendaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportarAgendaActionPerformed
        // TODO add your handling code here:
    if (indice < 5) {
        
    JOptionPane.showMessageDialog(this, "Faltan tareas por ingresar");
    return;
   }

    try (FileWriter fw = new FileWriter("temp/ismael_agenda.txt")) {
    fw.write("Agenda de Tareas\n");
    for (int i = 0; i < tareas.length; i++) {
        fw.write((i + 1) + ". " + tareas[i] + "\n");
    }
    JOptionPane.showMessageDialog(this, "Agenda exportada en la carpeta temp");
    } catch (IOException ex) {
    System.out.println("Error al escribir: " + ex.getMessage());
    }    
        
        
    }//GEN-LAST:event_btnExportarAgendaActionPerformed

