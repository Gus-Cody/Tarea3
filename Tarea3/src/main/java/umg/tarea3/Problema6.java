    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
      
        String titulo = txtTitulo.getText().trim();
        String consola = txtConsola.getText().trim();
        
        if (titulo.isEmpty() || consola.isEmpty()) {
        
            
            JOptionPane.showMessageDialog(this, "Completa el título y la consola");
        return;
        }
        
        int anio;
        
        try {
        anio = Integer.parseInt(txtAnio.getText().trim());
        }
        
        catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "El año debe ser un número entero");
        return;
        }
        
        Videojuego juego = new Videojuego(titulo, consola, anio);
        catalogo.add(juego);
        
        txtTitulo.setText("");
        txtConsola.setText("");
        txtAnio.setText("");
        
        
        
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnMostarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMostarActionPerformed
        // TODO add your handling code here:
        
            taInventario.setText("");

    for (int i = 0; i < catalogo.size(); i++) {
    Videojuego v = catalogo.get(i);
    taInventario.append((i + 1) + ". " + v.titulo + " | " + v.consola + " | " + v.anioLanzamiento + "\n");
    }

taInventario.append("\nTotal de juegos: " + catalogo.size());
    }//GEN-LAST:event_btnMostarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        
              if (catalogo.size() > 0) {
   
                  Videojuego eliminado = catalogo.remove(catalogo.size() - 1);
    
                  JOptionPane.showMessageDialog(this, "Se eliminó: " + eliminado.titulo);
    } else {
    JOptionPane.showMessageDialog(this, "El catálogo está vacío");
    } 
    }//GEN-LAST:event_btnEliminarActionPerformed

